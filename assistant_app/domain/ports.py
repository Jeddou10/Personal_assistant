"""Dependency boundaries; implementations live outside the application core."""

from collections.abc import Callable
from typing import Protocol

from .models import JsonObject, Settings


class StorePort(Protocol):
    @property
    def revision(self) -> int: ...
    def load_settings(self) -> Settings: ...
    def save_settings(self, settings: Settings) -> None: ...
    def get_secret(self, name: str) -> str: ...
    def set_secret(self, name: str, value: str) -> None: ...
    def load_preferences(self) -> list[str]: ...
    def save_preferences(self, preferences: list[str]) -> None: ...


class IntegrationsPort(Protocol):
    def search_mail(self, query: str) -> JsonObject: ...
    def read_mail(self, message_id: str) -> JsonObject: ...
    def list_events(self, time_min: str, time_max: str) -> JsonObject: ...
    def read_notion(self) -> JsonObject: ...
    def prepare(self, action: str, arguments: JsonObject) -> JsonObject: ...
    def execute(self, action: str, prepared: JsonObject) -> JsonObject: ...


class ProviderPort(Protocol):
    def complete(
        self, settings: Settings, store: StorePort, system: str, messages: list[JsonObject], tools: list[JsonObject]
    ) -> list[JsonObject]: ...


Completion = Callable[[Settings, StorePort, str, list[JsonObject], list[JsonObject]], list[JsonObject]]
IntegrationFactory = Callable[[Settings], IntegrationsPort]
